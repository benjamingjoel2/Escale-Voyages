/**
 * Regenerates lib/media.ts from the files in public/media.
 * Run after adding or replacing photos: `npm run media`.
 */
import { readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);
const sharp = require("sharp");

const dir = path.resolve("public/media");
const files = readdirSync(dir)
  .filter((f) => /\.(jpe?g|png|webp|avif)$/i.test(f))
  .sort();

const manifest = {};
for (const f of files) {
  const { width, height } = await sharp(path.join(dir, f)).metadata();
  manifest[f] = { width, height };
}

const out = `/**
 * Manifest of media files present in public/media, generated by
 * scripts/media-manifest.mjs (\`npm run media\`). MediaSlot renders a real
 * image only for files listed here.
 */
export const media: Record<string, { width: number; height: number }> = ${JSON.stringify(manifest, null, 2)};

export function mediaSrc(file: string): string | undefined {
  return file in media ? \`/media/\${file}\` : undefined;
}
`;
writeFileSync("lib/media.ts", out);
console.log(`${files.length} files written to lib/media.ts`);
